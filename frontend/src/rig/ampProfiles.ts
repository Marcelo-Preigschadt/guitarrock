export function valveCurve(
  drive: number,
  bias: number,
): Float32Array<ArrayBuffer> {
  const result = new Float32Array(4097),
    zero = Math.tanh(bias),
    scale = Math.max(
      Math.abs(Math.tanh(drive + bias) - zero),
      Math.abs(Math.tanh(-drive + bias) - zero),
    );
  for (let i = 0; i < result.length; i++) {
    const x = (2 * i) / (result.length - 1) - 1;
    result[i] = (Math.tanh(drive * x + bias) - zero) / scale;
  }
  return result;
}
